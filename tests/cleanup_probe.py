#!/usr/bin/python3
"""Remove only the denial/expiry rows created by a fresh live-test probe."""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import tcc_grant as t


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--bundle', required=True)
    parser.add_argument('--executable', required=True)
    args = parser.parse_args()
    # This is a test helper, not an escape hatch for conflicting production undo.
    if not re.fullmatch(r'dev\.tcc-grant\.test\.[0-9a-f]{12}', args.bundle):
        raise t.Error('Only fresh live-test bundle identifiers can be cleaned.')
    path = Path(args.executable).resolve()
    expected = Path(__file__).resolve().parents[1] / '.build'
    if expected not in path.parents or path.name != 'CLIProbe' or not path.parent.name.startswith('live-'):
        raise t.Error('Executable must belong to a live-test build directory.')
    t.require_root()
    t.check_environment()
    user = t.choose_user()
    databases, _ = t.discover_databases(user)
    with t.state_lock():
        for db in databases.values():
            c = t.connect(db)
            try:
                c.execute('BEGIN IMMEDIATE')
                # Each identity is freshly generated by the live-test runner.
                for client, typ in ((args.bundle, 0), (str(path), 1)):
                    for table in ('access', 'expired'):
                        if c.execute('SELECT 1 FROM sqlite_master WHERE name=?', (table,)).fetchone():
                            c.execute(f'DELETE FROM {table} WHERE client=? AND client_type=?', (client, typ))
                c.commit()
            finally:
                c.close()
    results = t.refresh(user.pw_uid, databases)
    if any(r['status'] == 'failed' for r in results):
        raise t.Error('Probe cleanup saved, but daemon refresh failed.')


if __name__ == '__main__':
    main()
